export function runtimeText(text: string, locale: GameLocale): string {
  if(locale === 'en') return text;
  if(text.startsWith('The model download could not start'))return text.replace('The model download could not start','模型下载无法启动');
  if(text.startsWith('The model download failed'))return text.replace('The model download failed','模型下载失败').replace('result','结果');
  if(text.startsWith('This GLB could not be imported'))return text.replace('This GLB could not be imported','此 GLB 模型无法导入');
  if(text.startsWith('Signal recovered · ')) return text.replace('Signal recovered','信号已恢复');
  return RUNTIME_ZH[text] ?? text;
}
